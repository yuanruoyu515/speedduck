const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'playwright');
const root = path.resolve(__dirname, '..');
(async () => {
  const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--disable-gpu'] });
  const context = await browser.newContext({ viewport: { width: 380, height: 660 }, deviceScaleFactor: 2 });
  await context.addInitScript({ path: path.join(root, 'extension/page.js') });
  const page = await context.newPage();
  await page.goto('data:text/html,<video id="v"></video><audio id="a"></audio>');
  async function configure(rate, force = true, pitch = true) {
    await page.evaluate(({rate, force, pitch}) => window.postMessage({ channel: 'speedduck:1', source: 'extension', type: 'config', config: {rate, force, pitch} }, '*'), {rate, force, pitch});
    await page.waitForTimeout(120);
  }
  await configure(2);
  assert.deepEqual(await page.evaluate(() => [v.playbackRate, a.playbackRate]), [2,2]);
  await page.evaluate(() => { v.playbackRate = 1; a.defaultPlaybackRate = 1; });
  assert.deepEqual(await page.evaluate(() => [v.playbackRate, a.defaultPlaybackRate]), [2,2]);
  await page.evaluate(() => { globalThis.dynamic = document.createElement('video'); document.body.append(dynamic); });
  await page.waitForTimeout(100);
  assert.equal(await page.evaluate(() => dynamic.playbackRate), 2);
  await page.evaluate(() => { const host = document.createElement('div'); document.body.append(host); globalThis.closedRoot = host.attachShadow({mode:'closed'}); closedRoot.innerHTML = '<video></video>'; });
  await page.waitForTimeout(100);
  assert.equal(await page.evaluate(() => closedRoot.querySelector('video').playbackRate), 2);
  await configure(3.5);
  assert.equal(await page.evaluate(() => closedRoot.querySelector('video').playbackRate), 3.5);
  await page.evaluate(() => { globalThis.spam = setInterval(() => { v.playbackRate = 1; }, 10); });
  await page.waitForTimeout(800);
  assert.equal(await page.evaluate(() => v.playbackRate), 3.5);
  await page.evaluate(() => clearInterval(spam));
  await configure(1.5, false, false);
  await page.evaluate(() => { v.playbackRate = .75; });
  await page.waitForTimeout(750);
  assert.equal(await page.evaluate(() => v.playbackRate), .75, 'force off releases the setter');
  assert.equal(await page.evaluate(() => a.preservesPitch), false);
  await configure(.25); assert.equal(await page.evaluate(() => v.playbackRate), .25);
  await configure(16); assert.equal(await page.evaluate(() => v.playbackRate), 16);
  await page.evaluate(() => { document.body.innerHTML = '<video id="replacement"></video>'; });
  await page.waitForTimeout(200);
  assert.equal(await page.evaluate(() => replacement.playbackRate), 16);
  console.log('PASS: actual Chromium media engine: lock, hostile resets, audio, dynamic media, closed shadow DOM, 0.25/16x, pitch, release');
  await context.close();

  const ui = await browser.newContext({ viewport: { width: 380, height: 600 }, deviceScaleFactor: 2 });
  await ui.addInitScript(() => {
    let state = { rate: 2, host: 'www.youtube.com', count: 2, force: true, pitch: true, rememberTab: false, rememberSite: false, limited: false, supported: true };
    globalThis.chrome = { tabs: { async query() { return [{id:1}]; }, async sendMessage() { return {alive:true}; } }, runtime: { async sendMessage(m) { if (m.patch) state = {...state,...m.patch}; return {ok:true,data:state}; } } };
  });
  const popup = await ui.newPage();
  await popup.goto(`file://${root}/extension/popup.html`);
  await popup.waitForFunction(() => document.getElementById('status').textContent.includes('已连接'));
  const bounds = await popup.evaluate(() => ({ width: document.documentElement.scrollWidth, height: document.documentElement.scrollHeight }));
  assert.equal(bounds.width, 380, 'no horizontal overflow');
  assert.ok(bounds.height <= 600, `popup fits browser height limit: ${bounds.height}`);
  await popup.setViewportSize({width: 380, height: bounds.height});
  await popup.waitForTimeout(300);
  await popup.screenshot({path: process.env.PREVIEW_PATH || path.join(root, 'test-results/popup.png'), fullPage:true});
  await popup.locator('[data-rate="3"]').click();
  await popup.waitForFunction(() => document.getElementById('speed-value').textContent === '3.00');
  await popup.locator('#plus').click();
  await popup.waitForFunction(() => document.getElementById('speed-value').textContent === '3.25');
  await popup.locator('#remember-site').check({force:true});
  await popup.locator('#details-toggle').click();
  assert.equal(await popup.locator('#details').isVisible(), true);
  await popup.locator('#speed-display').click();
  await popup.locator('#custom-speed').fill('8');
  await popup.locator('#custom-form button').click();
  await popup.waitForFunction(() => document.getElementById('speed-value').textContent === '8.00');
  assert.equal(await popup.locator('#speed-slider').getAttribute('max'), '16');
  await popup.locator('#reset').click();
  await popup.waitForFunction(() => document.getElementById('speed-value').textContent === '1.00');
  console.log('PASS: popup controls, custom rate, presets, switches, details, bounds, reset; saved UI screenshot');
  await browser.close();
})().catch(e => {console.error(e); process.exit(1);});
